//! (c) 2020 Wenzel Jakob. See `data/NOTICE`. D65 and D60 are already divided
//! by the luminance normalisers in that header. The D60 table there has 94
//! initialisers for a 95-element array, so the last sample is zero, matching
//! C++'s rule for a missing initialiser. The colour-matching functions are
//! the CIE 1931 2 degree standard observer.
